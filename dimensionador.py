def ilum_va(area):
    """100 VA nos primeiros 6 m² + 60 VA a cada 4 m² inteiros adicionais."""
    if area <= 6:
        return 100
    return 100 + 60 * int((area - 6 + 1e-9) // 4)


def tug_qtd(tp, area, perim):
    if tp["p35"]:                      # cozinha, copa, área de serviço
        return max(1, ceil_(perim / 3.5))
    if tp["nome"] == "Banheiro":
        return 1
    if area <= 6:
        return 1
    return max(1, ceil_(perim / 5))


def tug_va(tp, n):
    if tp["serv"]:                     # 600 VA nas 3 primeiras, 100 VA nas demais
        return 600 * min(n, 3) + 100 * max(n - 3, 0)
    return 100 * n


