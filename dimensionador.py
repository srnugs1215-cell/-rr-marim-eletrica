def fmt(x, d=1):
    """Número no formato brasileiro (vírgula decimal)."""
    return f"{x:.{d}f}".replace(".", ",")


def fmt_s(s):
    """Seção do condutor: 1,5 / 2,5 / 4 / 6 ..."""
    return str(s).replace(".", ",") if isinstance(s, float) and s != int(s) else str(int(s))


def ceil_(x):
    return int(math.ceil(x - 1e-9))


def slug(texto):
    t = unicodedata.normalize("NFKD", texto).encode("ascii", "ignore").decode()
    t = re.sub(r"[^A-Za-z0-9]+", "_", t).strip("_")
    return t or "dimensionamento"


_SUBS = {"–": "-", "—": "-", "•": "-", "≤": "<=", "≥": ">=", "→": "->",
         "’": "'", "‘": "'", "“": '"', "”": '"', "…": "...", "Ω": "ohm",
         "√": "raiz de ", "ρ": "rho", "Δ": "Delta ", "²": "2"}


def T(s):
    """Deixa o texto compatível com as fontes padrão do PDF (latin-1)."""
    s = str(s)
    for k, v in _SUBS.items():
        s = s.replace(k, v)
    return s.encode("latin-1", "replace").decode("latin-1")


