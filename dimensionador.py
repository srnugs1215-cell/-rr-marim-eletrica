def ajustar(pdf, texto, largura):
    t = T(texto)
    if pdf.get_string_width(t) <= largura - 2:
        return t
    while len(t) > 1 and pdf.get_string_width(t + "...") > largura - 2:
        t = t[:-1]
    return t + "..."


