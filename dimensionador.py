def pergunta(msg, padrao=None):
    suf = f" [{padrao}]" if padrao not in (None, "") else ""
    r = input(f"{msg}{suf}: ").strip()
    if r == "" and padrao is not None:
        return str(padrao)
    return r


def num(msg, padrao=None, minimo=None, maximo=None):
    while True:
        txt = None if padrao is None else str(padrao).replace(".", ",")
        r = pergunta(msg, txt)
        try:
            v = float(r.replace(",", "."))
        except ValueError:
            print("  Número inválido, tente de novo.")
            continue
        if minimo is not None and v < minimo:
            print(f"  O mínimo é {minimo}.")
            continue
        if maximo is not None and v > maximo:
            print(f"  O máximo é {maximo}.")
            continue
        return v


def inteiro(msg, padrao=None, minimo=None):
    return int(num(msg, padrao, minimo))


def escolha(msg, opcoes, padrao=None):
    print(msg)
    for i, o in enumerate(opcoes, 1):
        print(f"  {i}) {o}")
    while True:
        r = pergunta("Opção", padrao)
        if r.isdigit() and 1 <= int(r) <= len(opcoes):
            return int(r)
        print("  Opção inválida.")


def sim_nao(msg, padrao=True):
    r = input(f"{msg} [{'S/n' if padrao else 's/N'}]: ").strip().lower()
    if r == "":
        return padrao
    return r in ("s", "sim", "y", "yes")


def listar_tipos():
    for k, t in TIPOS.items():
        print(f"  {k:>2}) {t['nome']}")


def cadastrar_comodos(dist_padrao):
    comodos = []
    print("\n=== CÔMODOS ===")
    print("Digite o número do tipo do cômodo.")
    print("0 = terminar | d = desfazer o último | l = ver a lista de tipos")
    listar_tipos()
    while True:
        r = input("\nTipo do cômodo: ").strip().lower()
        if r == "l":
            listar_tipos()
            continue
        if r == "0":
            if not comodos:
                print("  Cadastre pelo menos 1 cômodo.")
                continue
            break
        if r == "d":
            if comodos:
                print(f"  Removido: {comodos.pop()['nome']}")
            else:
                print("  Não há cômodos para remover.")
            continue
        if not r.isdigit() or int(r) not in TIPOS:
            print("  Tipo inválido.")
            continue
        k = int(r)
        tp = TIPOS[k]
        anteriores = sum(1 for c in comodos if c["tipo"] == k)
        padrao_nome = tp["nome"] if anteriores == 0 else f"{tp['nome']} {anteriores + 1}"
        nome = pergunta("Nome", padrao_nome)
        area = num("Área (m²)", minimo=0.5)
        perim = num("Perímetro (m)", round(4 * math.sqrt(area), 1), minimo=1)
        dist = num("Distância do quadro até o cômodo (m)", dist_padrao, minimo=0)
        il = ilum_va(area)
        tq = tug_qtd(tp, area, perim)
        print(f"  NBR 5410 sugere: iluminação {il} VA | {tq} tomada(s) = {tug_va(tp, tq)} VA")
        il = num("Iluminação (VA)", il, minimo=0)
        tq = inteiro("Quantidade de TUG", tq, minimo=0)
        comodos.append(dict(tipo=k, nome=nome, area=area, perim=perim, dist=dist,
                            ilum_va=il, tug_qtd=tq, tug_va=tug_va(tp, tq)))
        print(f"  OK: {nome} adicionado ({len(comodos)} cômodo(s)).")
    return comodos


def cadastrar_tues(nf, vf, vl, dist_padrao):
    tues = []
    print("\n=== CARGAS ESPECÍFICAS (TUE) ===")
    print("Ex.: chuveiro, ar-condicionado, forno, máquina de lavar...")
    print("Nome vazio = terminar | d = desfazer a última")
    while True:
        nome = input("\nNome da carga: ").strip()
        if nome == "":
            break
        if nome.lower() == "d":
            if tues:
                print(f"  Removida: {tues.pop()['nome']}")
            else:
                print("  Não há cargas para remover.")
            continue
        pot = num("Potência (W)", minimo=1)
        opcoes, modos = [f"{vf:g} V (fase + neutro)"], ["fn"]
        if nf >= 2:
            opcoes.append(f"{vl:g} V (fase + fase)")
            modos.append("ff")
        if nf == 3:
            opcoes.append(f"{vl:g} V trifásico (3 fases)")
            modos.append("tri")
        modo = modos[0] if len(modos) == 1 else modos[escolha("Ligação:", opcoes) - 1]
        fp = num("Fator de potência", 1, minimo=0.3, maximo=1)
        qtd = inteiro("Quantidade (cada uma com circuito próprio)", 1, minimo=1)
        dist = num("Distância do quadro até a carga (m)", dist_padrao, minimo=0)
        molhada = sim_nao("Fica em área molhada (banheiro, cozinha, externa)?", False)
        tues.append(dict(nome=nome, pot_w=pot, modo=modo, fp=fp, qtd=qtd, dist=dist,
                         molhada=molhada))
        print(f"  OK: {nome} adicionado.")
    return tues


def novo_projeto():
    print("\n=== NOVO DIMENSIONAMENTO ===")
    nome = ""
    while not nome:
        nome = input("Nome do dimensionamento (ex.: Casa João Silva): ").strip()
    cliente = input("Cliente (Enter para pular): ").strip()
    local = input("Endereço/local (Enter para pular): ").strip()

    s = escolha("Sistema de tensão:", ["127/220 V", "220/380 V"], 1)
    vf, vl = SISTEMAS[s]
    f = escolha("Fornecimento:", [FORNECIMENTOS[k][0] for k in sorted(FORNECIMENTOS)], 1)
    nf = FORNECIMENTOS[f][1]

    par = dict(vf=vf, vl=vl, nfases=nf, queda_circ=3.0, queda_alim=2.0,
               circ_por_eletroduto=3, aplicar_fd=True, dist_medidor=10.0)
    par["dist_medidor"] = num("Distância do medidor até o quadro (m)", 10, minimo=0)
    if not sim_nao("Usar parâmetros padrão (queda 3% + 2%, 3 circuitos por eletroduto, "
                   "fator de demanda)?", True):
        par["queda_circ"] = num("Queda máx. no circuito terminal (%)", 3, minimo=0.5, maximo=4)
        par["queda_alim"] = num("Queda máx. no alimentador (%)", 2, minimo=0.2, maximo=4)
        par["circ_por_eletroduto"] = inteiro("Máx. de circuitos no mesmo eletroduto", 3, minimo=1)
        par["aplicar_fd"] = sim_nao("Aplicar fator de demanda?", True)

    comodos = cadastrar_comodos(10)
    tues = cadastrar_tues(nf, vf, vl, 10)
    return dict(nome=nome, cliente=cliente, local=local,
                data=date.today().strftime("%d/%m/%Y"), params=par,
                comodos=comodos, tues=tues)


