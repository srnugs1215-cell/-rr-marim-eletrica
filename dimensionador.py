def fca_agrupamento(n):
    n = max(1, int(n))
    for k in sorted(FCA):
        if k >= n:
            return FCA[k]
    return FCA[20]


def fd_ilum_tug(kw):
    for lim, fd in FD_ILUM_TUG:
        if kw <= lim:
            return fd
    return 0.24


def fd_tue(n):
    if n <= 0:
        return 1.0
    return FD_TUE.get(n, 0.38)


def corrente(va, modo, vf, vl):
    if modo == "fn":
        return va / vf
    if modo == "ff":
        return va / vl
    return va / (math.sqrt(3) * vl)


def queda_pct(i, comp, s, modo, vf, vl):
    if modo == "fn":
        return 2 * RHO * comp * i / s / vf * 100
    if modo == "ff":
        return 2 * RHO * comp * i / s / vl * 100
    return math.sqrt(3) * RHO * comp * i / s / vl * 100


def proximo_disjuntor(ib, minimo=0):
    for d in DISJUNTORES:
        if d >= ib and d >= minimo:
            return d
    return None


def secao_pe(s):
    if s <= 16:
        return s
    if s <= 35:
        return 16
    return {50: 25, 70: 35, 95: 50}.get(s, s / 2)


def dimensionar(ib, comp, tipo, modo, fca, qmax, vf, vl, in_min=0):
    """Escolhe disjuntor e seção: Ib <= In <= Iz e queda de tensão <= limite."""
    iz_tab = IZ_3 if modo == "tri" else IZ_2
    smin = 1.5 if tipo == "ilum" else 2.5
    in_a = proximo_disjuntor(ib, in_min)
    if in_a is None:
        s = SECOES[-1]
        return dict(secao=s, iz=iz_tab[s] * fca, in_a=DISJUNTORES[-1],
                    queda=queda_pct(ib, comp, s, modo, vf, vl), ok=False)
    for s in SECOES:
        if s < smin:
            continue
        iz = iz_tab[s] * fca
        q = queda_pct(ib, comp, s, modo, vf, vl)
        if iz >= in_a and q <= qmax:
            return dict(secao=s, iz=iz, in_a=in_a, queda=q, ok=True)
    s = SECOES[-1]
    return dict(secao=s, iz=iz_tab[s] * fca, in_a=in_a,
                queda=queda_pct(ib, comp, s, modo, vf, vl), ok=False)


def agrupar(itens, limite_va):
    grupos, atual, soma = [], [], 0.0
    for it in itens:
        if atual and soma + it["va"] > limite_va:
            grupos.append(atual)
            atual, soma = [], 0.0
        atual.append(it)
        soma += it["va"]
    if atual:
        grupos.append(atual)
    return grupos


def distribuir_fases(circuitos, nf):
    letras = ["A", "B", "C"][:nf]
    carga = {f: 0.0 for f in letras}
    if nf == 1:
        for c in circuitos:
            c["fase"] = "A"
            carga["A"] += c["va"]
        return carga
    pares = list(itertools.combinations(letras, 2))
    for c in sorted(circuitos, key=lambda x: -x["va"]):
        if c["modo"] == "fn":
            f = min(letras, key=lambda x: carga[x])
            c["fase"] = f
            carga[f] += c["va"]
        elif c["modo"] == "ff":
            p = min(pares, key=lambda x: carga[x[0]] + carga[x[1]])
            c["fase"] = "-".join(p)
            for f in p:
                carga[f] += c["va"] / 2
        else:
            c["fase"] = "-".join(letras)
            for f in letras:
                carga[f] += c["va"] / 3
    return carga


def calcular(proj):
    par = proj["params"]
    vf, vl, nf = par["vf"], par["vl"], par["nfases"]
    fca = fca_agrupamento(par["circ_por_eletroduto"])
    qc, qa = par["queda_circ"], par["queda_alim"]
    avisos = []
    circ = []

    def add_grupo(prefixo, tipo, itens, limite_a, in_min):
        grupos = agrupar(itens, limite_a * vf)
        for k, g in enumerate(grupos, 1):
            nome = prefixo if len(grupos) == 1 else f"{prefixo} {k}"
            circ.append(dict(
                nome=nome, desc=", ".join(i["nome"] for i in g), tipo=tipo,
                modo="fn", va=sum(i["va"] for i in g),
                dist=max(i["dist"] for i in g),
                dr=any(i["dr"] for i in g), in_min=in_min))

    # Iluminação
    il = [dict(va=c["ilum_va"], dist=c["dist"], nome=c["nome"],
               dr=TIPOS[c["tipo"]]["dr_ilum"]) for c in proj["comodos"]]
    add_grupo("Iluminação", "ilum", il, LIM_ILUM_A, MIN_DISJ_ILUM)

    # TUG - áreas de serviço/úmidas separadas das demais
    tg_serv = [dict(va=c["tug_va"], dist=c["dist"], nome=c["nome"],
                    dr=TIPOS[c["tipo"]]["dr_tug"])
               for c in proj["comodos"] if TIPOS[c["tipo"]]["serv"]]
    tg_geral = [dict(va=c["tug_va"], dist=c["dist"], nome=c["nome"],
                     dr=TIPOS[c["tipo"]]["dr_tug"])
                for c in proj["comodos"] if not TIPOS[c["tipo"]]["serv"]]
    if tg_serv:
        add_grupo("TUG cozinha/serviço/banheiro", "tug", tg_serv, LIM_TUG_A, MIN_DISJ_TUG)
    if tg_geral:
        add_grupo("TUG demais cômodos", "tug", tg_geral, LIM_TUG_A, MIN_DISJ_TUG)

    # TUE - um circuito exclusivo por equipamento
    for t in proj["tues"]:
        for k in range(t["qtd"]):
            nome = t["nome"] if t["qtd"] == 1 else f"{t['nome']} {k + 1}"
            circ.append(dict(
                nome=nome, desc=nome, tipo="tue", modo=t["modo"],
                va=t["pot_w"] / t["fp"], dist=t["dist"], dr=t["molhada"],
                in_min=0))

    # Dimensionamento de cada circuito
    for n, c in enumerate(circ, 1):
        c["num"] = n
        c["ib"] = corrente(c["va"], c["modo"], vf, vl)
        c.update(dimensionar(c["ib"], c["dist"], c["tipo"], c["modo"], fca,
                             qc, vf, vl, c["in_min"]))
        c["polos"] = POLOS[c["modo"]]
        c["tensao"] = vf if c["modo"] == "fn" else vl
        c["neutro"] = c["secao"] if c["modo"] == "fn" else None
        c["pe"] = secao_pe(c["secao"])
        if not c["ok"]:
            avisos.append(f"Circuito {n} ({c['nome']}): não foi possível atender "
                          f"corrente/queda de tensão até 95 mm². Dimensionar manualmente.")

    carga_fase = distribuir_fases(circ, nf)

    # Demanda
    s_it = sum(c["va"] for c in circ if c["tipo"] in ("ilum", "tug"))
    s_tue = sum(c["va"] for c in circ if c["tipo"] == "tue")
    n_tue = sum(1 for c in circ if c["tipo"] == "tue")
    if par["aplicar_fd"]:
        fd1, fd2 = fd_ilum_tug(s_it / 1000.0), fd_tue(n_tue)
    else:
        fd1, fd2 = 1.0, 1.0
    d1, d2 = s_it * fd1, s_tue * fd2
    dem = d1 + d2

    tot_fase = sum(carga_fase.values()) or 1.0
    share = max(carga_fase.values()) / tot_fase
    i_dem = dem * share / vf

    # Alimentador geral
    modo_al = {1: "fn", 2: "ff", 3: "tri"}[nf]
    al = dimensionar(i_dem, par["dist_medidor"], "alim", modo_al, 1.0, par["queda_alim"],
                     vf, vl, 0)
    al["modo"] = modo_al
    al["i_dem"] = i_dem
    al["pe"] = secao_pe(al["secao"])
    if not al["ok"]:
        avisos.append("Alimentador geral: não foi possível dimensionar até 95 mm². "
                      "Dimensionar manualmente.")

    for c in circ:
        c["queda_total"] = c["queda"] + al["queda"]
        if c["queda_total"] > 5.0:
            avisos.append(f"Circuito {c['num']} ({c['nome']}): queda total "
                          f"{fmt(c['queda_total'])}% acima de 5%.")

    desequilibrio = 0.0
    if nf > 1:
        med = tot_fase / nf
        desequilibrio = (max(carga_fase.values()) - med) / med * 100 if med else 0.0

    return dict(circuitos=circ, carga_fase=carga_fase, desequilibrio=desequilibrio,
                s_it=s_it, fd1=fd1, d1=d1, s_tue=s_tue, n_tue=n_tue, fd2=fd2, d2=d2,
                dem=dem, alim=al, fca=fca, avisos=avisos,
                total_inst=s_it + s_tue)


